export const STATIC_NOINDEX_FOLLOW_PATHS = Object.freeze([
  '/pricing',
  '/refund-policy',
  '/tools/ai-image-prompts/trending',
  '/vip-creator-club',
]);

const GROUP_B_SET = new Set(GROUP_B_LOW_VALUE_PROMPT_SLUGS);
const CRITICALLY_THIN_SET = new Set(CRITICALLY_THIN_PROMPT_SLUGS);
const GSC_CLICK_EXCEPTION_SET = new Set(GSC_CLICK_EXCEPTION_PROMPT_SLUGS);
const EXISTING_NOINDEX_SET = new Set(AUDITED_EXISTING_NOINDEX_PROMPT_SLUGS);
const REQUESTED_NOINDEX_SET = new Set(REQUESTED_NOINDEX_PROMPT_SLUGS);
const STATIC_NOINDEX_FOLLOW_SET = new Set(STATIC_NOINDEX_FOLLOW_PATHS);

export function isLowValuePromptSlug(slug = '') {
  const normalized = String(slug || '').trim().toLowerCase();
  if (GSC_CLICK_EXCEPTION_SET.has(normalized)) return false;
  return GROUP_B_SET.has(normalized)
    || CRITICALLY_THIN_SET.has(normalized)
    || REQUESTED_NOINDEX_SET.has(normalized);
}

export function isAuditedNoIndexPromptSlug(slug = '') {
  const normalized = String(slug || '').trim().toLowerCase();
  return isLowValuePromptSlug(normalized) || EXISTING_NOINDEX_SET.has(normalized);
}

export function isStaticNoIndexFollowPath(pathname = '') {
  return STATIC_NOINDEX_FOLLOW_SET.has(normalizePathname(pathname));
}

function normalizePathname(pathname = '/') {
  const clean = String(pathname || '/').split(/[?#]/, 1)[0] || '/';
  if (clean === '/') return clean;
  return clean.replace(/\/+$/, '');
}
